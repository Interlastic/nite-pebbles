def make_loading_bar(current: float, size=10):
    """
    Create a loading bar with proper rounded ends and padding at transition.
    """
    # Clamp current to valid range
    current = max(0, min(current, size * 10))
    
    # Calculate percentage (0.0 to 1.0)
    percentage = current / (size * 10)
    
    # Special case: single segment bar
    if size == 1:
        # Map percentage to level 1-30 (1 = full green, 30 = full red)
        level = 30 - round(percentage * 29)
        level = max(1, min(30, level))
        return EMOJIS_END_BOTH[level]
    
    # For multi-segment bars
    # Calculate how many full green segments we need
    filled_segments = percentage * size
    full_green_count = int(filled_segments)
    
    # Calculate the partial fill level for the transition segment
    partial_fill = filled_segments - full_green_count
    
    # Map partial_fill to level (1 = full green, 30 = full red)
    transition_level = 30 - round(partial_fill * 29)
    transition_level = max(1, min(30, transition_level))
    
    result = ""
    
    # Edge case: 0% - all red
    if current <= 0:
        result += EMOJIS_END_GREEN[30] 
        for _ in range(size - 2):
            result += EMOJIS_NORMAL[30] 
        result += EMOJIS_END_RED[30]
        return result
    
    # Edge case: 100% - all green
    if current >= size * 10:
        result += EMOJIS_END_GREEN[1]
        for _ in range(size - 2):
            result += EMOJIS_NORMAL[1]
        result += EMOJIS_END_RED[1]
        return result
    
    transition_index = full_green_count
    
    for i in range(size):
        is_first = (i == 0)
        is_last = (i == size - 1)
        is_transition = (i == transition_index)
        is_after_transition = (i == transition_index + 1) if transition_index < size - 1 else False
        
        if i < transition_index:
            if is_first:
                result += EMOJIS_END_GREEN[1]
            else:
                result += EMOJIS_NORMAL[1]
        
        elif is_transition:
            if is_first:
                if is_last:
                    result += EMOJIS_END_BOTH[transition_level]
                else:
                    result += EMOJIS_END_GREEN[transition_level]
            elif is_last:
                result += EMOJIS_END_RED[transition_level]
            else:
                result += EMOJIS_END_RED[transition_level]
        
        elif is_after_transition:
            if is_last:
                result += EMOJIS_END_RED[30]
            else:
                result += EMOJIS_END_GREEN[30]
        
        else:
            if is_last:
                result += EMOJIS_END_RED[30]
            else:
                result += EMOJIS_NORMAL[30]
    
    return result

import re

def format_number(val, precision=None):
    if precision == "raw":
        return str(val)
        
    if val < 1000:
        return str(val)
    
    if val >= 1_000_000:
        res = val / 1_000_000
        unit = "M"
    else:
        res = val / 1_000
        unit = "K"
    
    if precision is not None:
        try:
            return f"{res:.{int(precision)}f}{unit}"
        except:
            return f"{res:g}{unit}"
    else:
        return f"{res:g}{unit}"

def render_template(template, guild):
    if not template:
        return None
    
    stats = {
        "members": getattr(guild, 'member_count', 0) or 0,
        "channels": len(guild.channels) if hasattr(guild, 'channels') else 0,
        "boost_level": getattr(guild, 'premium_tier', 0) or 0,
        "boost_count": getattr(guild, 'premium_subscription_count', 0) or 0
    }
    
    def replacer(match):
        var = match.group(1)
        precision = match.group(3) # group 3 is the value after the comma
        
        if var in stats:
            val = stats[var]
            return format_number(val, precision)
        return match.group(0)
    
    return re.sub(r"\{(\w+)(,(\w+))?\}", replacer, template)
